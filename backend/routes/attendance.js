const express = require('express');
const router = express.Router();
const { authenticateToken, isAdmin, isHR, isManager, isManagerOrHR } = require('../middleware/authMiddleware');
const attendanceController = require('../controllers/attendanceController');

router.post('/check-in', authenticateToken, attendanceController.checkIn);
router.post('/check-out', authenticateToken, attendanceController.checkOut);
router.get('/today', authenticateToken, attendanceController.getToday);
router.get('/my-attendance', authenticateToken, attendanceController.getMyAttendance);
router.get('/pending-approvals', authenticateToken, isManagerOrHR, attendanceController.getPendingApprovals);
router.post('/approve/:attendanceId', authenticateToken, isManagerOrHR, attendanceController.approveAttendance);
router.post('/decline/:attendanceId', authenticateToken, isManagerOrHR, attendanceController.declineAttendance);
router.post('/mark-late/:attendanceId', authenticateToken, isManagerOrHR, attendanceController.markLate);
router.post('/override/:attendanceId', authenticateToken, isAdmin, attendanceController.overrideAttendance);
router.post('/correction-request', authenticateToken, attendanceController.correctionRequest);
router.post('/correction-review/:attendanceId', authenticateToken, isManagerOrHR, attendanceController.correctionReview);
router.get('/report', authenticateToken, isManagerOrHR, attendanceController.getReport);
router.get('/audit-log/:attendanceId', authenticateToken, isManagerOrHR, attendanceController.getAuditLog);
router.get('/approval-history', authenticateToken, isManagerOrHR, attendanceController.getApprovalHistory);
router.get('/escalation-log', authenticateToken, attendanceController.getEscalationLog);
router.get('/my-escalations', authenticateToken, attendanceController.getMyEscalations);
router.get('/team-attendance', authenticateToken, isManagerOrHR, attendanceController.getTeamAttendance);
module.exports = router;